#!/usr/bin/env python3
"""Evaluate a validation-selected crop-aware hybrid forecast.

Reads the validation ensemble predictions generated by evaluate_ensemble.py.
The candidate rule is deliberately simple:
  * onion, tomato: use the median of the five LSTM predictions
  * all other crops: use the last-month-naive prediction

This script evaluates validation data only. Because the rule was selected after
reviewing validation results, its validation metrics are exploratory and must
not be treated as an unbiased final performance estimate. Freeze the rule
before opening the untouched test split.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

KEYS = ["crop", "state", "target_month"]
LSTM_CROPS = {"onion", "tomato"}
REQUIRED = KEYS + [
    "actual_baseline",
    "pred_last_month_naive",
    "pred_median_ensemble",
]


def calculate_metrics(actual: np.ndarray, predicted: np.ndarray) -> dict[str, float | int]:
    actual = np.asarray(actual, dtype=float)
    predicted = np.asarray(predicted, dtype=float)
    if actual.ndim != 1 or predicted.ndim != 1 or len(actual) == 0 or len(actual) != len(predicted):
        raise ValueError("Metric inputs must be non-empty, one-dimensional, and equal length")
    if not (np.isfinite(actual).all() and np.isfinite(predicted).all()):
        raise ValueError("Metric inputs contain NaN or infinite values")
    if np.any(actual <= 0):
        raise ValueError("Actual prices must be positive to calculate MAPE")
    error = predicted - actual
    return {
        "n": int(len(actual)),
        "mae_rs_qtl": float(np.mean(np.abs(error))),
        "rmse_rs_qtl": float(np.sqrt(np.mean(error**2))),
        "mape_pct": float(np.mean(np.abs(error / actual)) * 100.0),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        default="data/training/monthly_maharashtra/ensemble_evaluation/validation_ensemble_predictions.csv",
        help="CSV created by evaluate_ensemble.py",
    )
    parser.add_argument(
        "--output-dir",
        default="data/training/monthly_maharashtra/hybrid_evaluation",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    if not input_path.exists():
        raise FileNotFoundError(
            f"Cannot find {input_path}. Run experiments/monthly/evaluate_ensemble.py first."
        )

    frame = pd.read_csv(input_path)
    missing = sorted(set(REQUIRED) - set(frame.columns))
    if missing:
        raise ValueError(f"Input file is missing required columns: {missing}")
    frame = frame[REQUIRED].copy()
    for col in KEYS:
        frame[col] = frame[col].astype(str).str.strip()
    for col in ["actual_baseline", "pred_last_month_naive", "pred_median_ensemble"]:
        frame[col] = pd.to_numeric(frame[col], errors="coerce")
    numeric = ["actual_baseline", "pred_last_month_naive", "pred_median_ensemble"]
    if frame[numeric].isna().any().any():
        raise ValueError("Input contains missing or non-numeric price values")
    if not np.isfinite(frame[numeric].to_numpy(dtype=float)).all():
        raise ValueError("Input contains infinite price values")
    if (frame["actual_baseline"] <= 0).any():
        raise ValueError("Actual prices must be positive")
    if frame.duplicated(KEYS).any():
        raise ValueError("Input contains duplicate crop/state/month targets")

    crops = set(frame["crop"].str.lower())
    if not LSTM_CROPS.issubset(crops):
        raise ValueError(f"Input must include both {sorted(LSTM_CROPS)}; found {sorted(crops)}")

    use_lstm = frame["crop"].str.lower().isin(LSTM_CROPS)
    frame["hybrid_method"] = np.where(use_lstm, "median_lstm_ensemble", "last_month_naive")
    frame["pred_hybrid"] = np.where(
        use_lstm,
        frame["pred_median_ensemble"],
        frame["pred_last_month_naive"],
    )

    overall_rows = []
    for name, col in [
        ("last_month_naive", "pred_last_month_naive"),
        ("median_ensemble", "pred_median_ensemble"),
        ("crop_aware_hybrid", "pred_hybrid"),
    ]:
        row = {"predictor": name}
        row.update(calculate_metrics(frame["actual_baseline"].to_numpy(), frame[col].to_numpy()))
        overall_rows.append(row)
    overall = pd.DataFrame(overall_rows)

    crop_rows = []
    for crop, group in frame.groupby("crop", sort=True):
        for name, col in [
            ("last_month_naive", "pred_last_month_naive"),
            ("median_ensemble", "pred_median_ensemble"),
            ("crop_aware_hybrid", "pred_hybrid"),
        ]:
            row = {"crop": crop, "predictor": name}
            row.update(calculate_metrics(group["actual_baseline"].to_numpy(), group[col].to_numpy()))
            crop_rows.append(row)
    by_crop = pd.DataFrame(crop_rows)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    prediction_columns = KEYS + [
        "actual_baseline", "pred_last_month_naive", "pred_median_ensemble", "hybrid_method", "pred_hybrid"
    ]
    frame[prediction_columns].to_csv(output_dir / "hybrid_validation_predictions.csv", index=False)
    overall.to_csv(output_dir / "hybrid_validation_metrics_overall.csv", index=False)
    by_crop.to_csv(output_dir / "hybrid_validation_metrics_by_crop.csv", index=False)

    hybrid_row = overall.loc[overall["predictor"] == "crop_aware_hybrid"].iloc[0]
    naive_row = overall.loc[overall["predictor"] == "last_month_naive"].iloc[0]
    summary = {
        "evaluation_split": "validation_only",
        "test_data_loaded": False,
        "n_validation_targets": int(len(frame)),
        "selection_rule": {
            "onion": "median_ensemble_of_five_lstm_seeds",
            "tomato": "median_ensemble_of_five_lstm_seeds",
            "all_other_crops": "last_month_naive",
        },
        "overall_metrics": overall.to_dict(orient="records"),
        "hybrid_mae_improvement_vs_naive_pct": float(
            (naive_row["mae_rs_qtl"] - hybrid_row["mae_rs_qtl"]) / naive_row["mae_rs_qtl"] * 100.0
        ),
        "important_caveat": (
            "The crop-routing rule was selected after inspecting validation results. "
            "These validation metrics are exploratory and may be optimistic. Freeze the rule "
            "before evaluating the untouched test split; do not further tune it on test data."
        ),
    }
    with (output_dir / "hybrid_experiment_summary.json").open("w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print("\n--- VALIDATION HYBRID METRICS (Rs./quintal) ---")
    print(overall.to_string(index=False, formatters={
        "mae_rs_qtl": "{:,.2f}".format,
        "rmse_rs_qtl": "{:,.2f}".format,
        "mape_pct": "{:.2f}".format,
    }))
    print("\n--- HYBRID DECISION BY CROP ---")
    print(
        frame.groupby(["crop", "hybrid_method"], sort=True).size()
        .reset_index(name="n")
        .to_string(index=False)
    )
    print(f"\nSaved hybrid validation evaluation to: {output_dir}")
    print("Caution: routing was selected using validation results; test split remains untouched.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
